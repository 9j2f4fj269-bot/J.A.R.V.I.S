"""Advanced Node.js debugging tools.

`node_diagnose` runs JavaScript under a harness that captures uncaught exceptions,
unhandled promise rejections and process warnings, then maps every stack frame back
to numbered source lines and explains the failure in plain words.

`node_check` finds syntax errors without executing anything.
`node_profile` records a CPU (or heap) profile and reports the hottest functions.
"""

from __future__ import annotations

import json
import os
import re
import secrets
import subprocess
from pathlib import Path

from .js import MAX_OUTPUT, _truncate, node_binary, pick_extension
from .node_diagnostics import diagnostic_report, parse_stack

HARNESS = r"""// Generated by JARVIS: captures failures instead of letting them escape.
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import fs from 'node:fs';

const target = process.env.JARVIS_TARGET;
const outFile = process.env.JARVIS_DIAG_OUT;
const asEsm = process.env.JARVIS_ESM === '1';
const argv = JSON.parse(process.env.JARVIS_ARGS || '[]');
const report = { errors: [], warnings: [], exit_code: null };

const serialise = (value) => {
  if (value instanceof Error) {
    return {
      name: value.name,
      message: value.message,
      code: value.code ?? null,
      stack: value.stack ?? null,
      cause: value.cause
        ? {
            name: value.cause.name ?? null,
            message: String(value.cause.message ?? value.cause),
            code: value.cause.code ?? null,
          }
        : null,
    };
  }
  return {
    name: typeof value,
    message: String(value),
    code: null,
    stack: new Error(String(value)).stack ?? null,
    cause: null,
  };
};

// Always overwrite: the exit handler must be able to publish the final state.
const flush = () => {
  if (!outFile) return;
  try { fs.writeFileSync(outFile, JSON.stringify(report)); } catch {}
};

process.argv = [process.argv[0], target, ...argv];

process.on('uncaughtException', (error) => {
  report.errors.push({ ...serialise(error), phase: 'uncaughtException' });
  flush();
  process.exit(1);
});
process.on('unhandledRejection', (reason) => {
  report.errors.push({ ...serialise(reason), phase: 'unhandledRejection' });
  flush();
});
process.on('warning', (warning) => {
  report.warnings.push({ name: warning.name, message: warning.message, stack: warning.stack ?? null });
});
process.on('exit', (code) => {
  report.exit_code = report.errors.length ? (code || 1) : code;
  flush();
});

try {
  if (asEsm) {
    await import(pathToFileURL(target).href);
  } else {
    createRequire(import.meta.url)(target);
  }
} catch (error) {
  report.errors.push({ ...serialise(error), phase: 'thrown' });
  flush();
  process.exit(1);
}

if (report.errors.length && !report.exit_code) report.exit_code = 1;
flush();
"""


def module_type(path: Path) -> str:
    """CommonJS or ESM, resolved the way Node itself does it."""
    if path.suffix == ".mjs":
        return "esm"
    if path.suffix == ".cjs":
        return "cjs"
    for parent in [path.parent, *path.parents]:
        manifest = parent / "package.json"
        if manifest.is_file():
            try:
                data = json.loads(manifest.read_text(encoding="utf-8"))
            except (ValueError, OSError):
                break
            return "esm" if data.get("type") == "module" else "cjs"
        if (parent / ".git").exists():
            break
    return "cjs"


def _base_dir(workspace: Path, cwd: str) -> Path:
    root = Path(workspace).resolve()
    base = (root / cwd).resolve() if cwd and cwd != "." else root
    if root != base and root not in base.parents:
        raise ValueError(f"cwd '{cwd}' is outside the workspace")
    base.mkdir(parents=True, exist_ok=True)
    return base


def _resolve_target(base: Path, path: str) -> Path:
    target = (base / path).resolve() if not Path(path).is_absolute() else Path(path).resolve()
    if not target.is_file():
        raise FileNotFoundError(f"no such file: {path}")
    return target


def run_diagnosed(
    workspace: Path,
    code: str | None = None,
    path: str | None = None,
    cwd: str = ".",
    timeout: int = 60,
    args: list[str] | None = None,
    node_flags: list[str] | None = None,
    span: int = 2,
) -> dict:
    node = node_binary()
    if not node:
        return {"ok": False, "error": "node is not installed; install Node.js 18+ to debug JavaScript"}

    base = _base_dir(workspace, cwd)
    created: Path | None = None
    try:
        if path:
            target = _resolve_target(base, path)
        elif code is not None:
            extension = pick_extension(code)
            target = base / f".jarvis_target_{secrets.token_hex(4)}{extension}"
            target.write_text(code, encoding="utf-8")
            created = target
        else:
            return {"ok": False, "error": "pass either code or path"}
    except (ValueError, FileNotFoundError) as exc:
        return {"ok": False, "error": str(exc)}

    esm = module_type(target) == "esm"
    token = secrets.token_hex(4)
    harness = base / f".jarvis_diag_{token}.mjs"
    report_file = base / f".jarvis_diag_{token}.json"
    harness.write_text(HARNESS, encoding="utf-8")

    flags = ["--enable-source-maps", "--stack-trace-limit=100", *(node_flags or [])]
    command = [node, *flags, str(harness)]
    env = {
        **os.environ,
        "JARVIS_TARGET": str(target),
        "JARVIS_ESM": "1" if esm else "0",
        "JARVIS_DIAG_OUT": str(report_file),
        "JARVIS_ARGS": json.dumps(args or []),
    }
    env.pop("NODE_NO_WARNINGS", None)  # warnings are part of the diagnosis
    timed_out = False
    stdout = stderr = ""
    exit_code = None
    try:
        proc = subprocess.run(
            command, cwd=str(base), capture_output=True, text=True,
            timeout=max(5, min(timeout, 300)), env=env,
        )
        stdout, stderr, exit_code = proc.stdout or "", proc.stderr or "", proc.returncode
    except subprocess.TimeoutExpired as exc:
        timed_out = True
        stdout = (exc.stdout or b"").decode() if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        stderr = (exc.stderr or b"").decode() if isinstance(exc.stderr, bytes) else (exc.stderr or "")

    report: dict = {}
    if report_file.is_file():
        try:
            report = json.loads(report_file.read_text(encoding="utf-8"))
        except (ValueError, OSError):
            report = {}

    for leftover in (harness, report_file):
        leftover.unlink(missing_ok=True)
    if created is not None:
        created.unlink(missing_ok=True)

    errors = report.get("errors") or []
    warnings = report.get("warnings") or []
    if timed_out:
        errors.append(
            {
                "name": "TimeoutError",
                "message": f"process did not exit within {timeout}s",
                "code": None,
                "stack": None,
                "phase": "timeout",
            }
        )

    diagnostics = diagnostic_report(
        errors,
        stderr,
        root=Path(workspace).resolve(),
        project_dir=base,
        span=span,
        include_scratch=created is not None,
        source_text=code,
    )
    return {
        "ok": not errors and not timed_out and (exit_code in (0, None)),
        "runtime": "node",
        "module_type": "esm" if esm else "cjs",
        "target": str(target),
        "exit_code": exit_code,
        "timed_out": timed_out,
        "stdout": _truncate(stdout),
        "stderr": _truncate(stderr),
        "errors": errors,
        "warnings": warnings,
        "frames": diagnostics["frames"],
        "app_frames": diagnostics["app_frames"],
        "suggestions": diagnostics["suggestions"],
    }


SYNTAX_LOCATION = re.compile(r"^(?P<file>.+?):(?P<line>\d+)\s*$")
SYNTAX_MESSAGE = re.compile(r"^(?P<name>SyntaxError|TypeError|ReferenceError):\s*(?P<message>.+)$")


def syntax_check(workspace: Path, path: str | None = None, code: str | None = None, cwd: str = ".") -> dict:
    node = node_binary()
    if not node:
        return {"ok": False, "error": "node is not installed"}
    base = _base_dir(workspace, cwd)
    created: Path | None = None
    try:
        if path:
            target = _resolve_target(base, path)
        elif code is not None:
            target = base / f".jarvis_check_{secrets.token_hex(4)}{pick_extension(code)}"
            target.write_text(code, encoding="utf-8")
            created = target
        else:
            return {"ok": False, "error": "pass either path or code"}
    except (ValueError, FileNotFoundError) as exc:
        return {"ok": False, "error": str(exc)}

    esm = module_type(target) == "esm"
    command = [node, "--check", str(target)]
    try:
        proc = subprocess.run(command, cwd=str(base), capture_output=True, text=True, timeout=60)
    finally:
        if created is not None:
            created.unlink(missing_ok=True)

    stderr = proc.stderr or ""
    if proc.returncode == 0 and not stderr.strip():
        return {"ok": True, "path": str(target), "module_type": "esm" if esm else "cjs", "message": "syntax OK"}

    location = None
    message = None
    for line in stderr.splitlines():
        stripped = line.strip()
        loc = SYNTAX_LOCATION.match(stripped)
        if loc and location is None:
            location = {"file": loc.group("file"), "line": int(loc.group("line"))}
        msg = SYNTAX_MESSAGE.match(stripped)
        if msg and message is None:
            message = {"name": msg.group("name"), "message": msg.group("message")}
    frames = parse_stack(stderr, Path(workspace).resolve())
    return {
        "ok": False,
        "path": str(target),
        "module_type": "esm" if esm else "cjs",
        "location": location,
        "error": message,
        "stderr": _truncate(stderr),
        "frames": frames,
        "suggestion": (
            "Fix the reported line first; Node never executed the file. "
            "If the error mentions 'import' or 'export', the module type is wrong "
            "(.mjs or package.json type=module)."
        ),
    }


def _profile_ratio(nodes: list[dict], hit_counts: dict[int, int], total: int, root: Path) -> list[dict]:
    rows = []
    for node in nodes:
        hits = hit_counts.get(node.get("id"), 0)
        if not hits:
            continue
        frame = node.get("callFrame") or {}
        url = frame.get("url") or ""
        if "node:internal" in url or not url:
            continue
        path = url[7:] if url.startswith("file://") else url
        try:
            relative = str(Path(path).resolve().relative_to(root))
        except (ValueError, OSError):
            relative = Path(path).name if path else "<native>"
        rows.append(
            {
                "function": frame.get("functionName") or "<anonymous>",
                "file": relative,
                "line": int(frame.get("lineNumber", -1)) + 1,
                "hits": hits,
                "percent": round(hits / total * 100, 1) if total else 0.0,
            }
        )
    rows.sort(key=lambda r: (-r["hits"], r["function"]))
    merged: dict[tuple, dict] = {}
    for row in rows:
        key = (row["function"], row["file"])
        if key in merged:
            merged[key]["hits"] += row["hits"]
            merged[key]["percent"] = round(merged[key]["hits"] / total * 100, 1) if total else 0.0
        else:
            merged[key] = dict(row)
    return sorted(merged.values(), key=lambda r: -r["hits"])


def _heap_rows(tree: dict, root: Path) -> tuple[list[dict], int]:
    rows: list[dict] = []
    total = 0

    def walk(node: dict) -> None:
        nonlocal total
        frame = node.get("callFrame") or {}
        size = node.get("selfSize", 0)
        total += size
        if size:
            url = frame.get("url") or ""
            if url and "node:internal" not in url:
                path = url[7:] if url.startswith("file://") else url
                try:
                    relative = str(Path(path).resolve().relative_to(root))
                except (ValueError, OSError):
                    relative = Path(path).name
                rows.append(
                    {
                        "function": frame.get("functionName") or "<anonymous>",
                        "file": relative,
                        "line": int(frame.get("lineNumber", -1)) + 1,
                        "bytes": size,
                    }
                )
        for child in node.get("children") or []:
            walk(child)

    walk(tree)
    rows.sort(key=lambda r: -r["bytes"])
    return rows[:15], total


def cpu_profile(
    workspace: Path,
    path: str | None = None,
    code: str | None = None,
    cwd: str = ".",
    timeout: int = 120,
    top: int = 10,
    kind: str = "cpu",
) -> dict:
    node = node_binary()
    if not node:
        return {"ok": False, "error": "node is not installed"}
    if kind not in {"cpu", "heap"}:
        return {"ok": False, "error": "kind must be 'cpu' or 'heap'"}
    base = _base_dir(workspace, cwd)
    created: Path | None = None
    try:
        if path:
            target = _resolve_target(base, path)
        elif code is not None:
            target = base / f".jarvis_prof_{secrets.token_hex(4)}{pick_extension(code)}"
            target.write_text(code, encoding="utf-8")
            created = target
        else:
            return {"ok": False, "error": "pass either path or code"}
    except (ValueError, FileNotFoundError) as exc:
        return {"ok": False, "error": str(exc)}

    root = Path(workspace).resolve()
    profile_dir = root / ".profiles"
    profile_dir.mkdir(exist_ok=True)
    name = f"{kind}-{secrets.token_hex(4)}.cpuprofile" if kind == "cpu" else f"{kind}-{secrets.token_hex(4)}.heapprofile"
    flags = ["--cpu-prof", f"--cpu-prof-dir={profile_dir}", f"--cpu-prof-name={name}", "--cpu-prof-interval=100"]
    if kind == "heap":
        # A small interval is required or tiny scripts sample nothing at all.
        flags = [
            "--heap-prof",
            "--heap-prof-interval=4096",
            f"--heap-prof-dir={profile_dir}",
            f"--heap-prof-name={name}",
        ]

    try:
        proc = subprocess.run(
            [node, *flags, str(target)], cwd=str(base), capture_output=True, text=True,
            timeout=max(5, min(timeout, 600)), env={**os.environ, "NODE_NO_WARNINGS": "1"},
        )
    except subprocess.TimeoutExpired:
        if created is not None:
            created.unlink(missing_ok=True)
        return {
            "ok": False,
            "error": f"process still running after {timeout}s, so no profile was written; "
            "profile a bounded script instead of a server",
        }

    profile_path = profile_dir / name
    if not profile_path.is_file():
        return {"ok": False, "error": "node wrote no profile file", "stderr": _truncate(proc.stderr or "")}

    try:
        data = json.loads(profile_path.read_text(encoding="utf-8"))
    except (ValueError, OSError) as exc:
        return {"ok": False, "error": f"could not read profile: {exc}"}

    result: dict = {
        "ok": True,
        "kind": kind,
        "profile_path": str(profile_path.relative_to(root)),
        "exit_code": proc.returncode,
        "stdout": _truncate(proc.stdout or ""),
        "stderr": _truncate(proc.stderr or ""),
        "target": target.name,
    }
    if created is not None:
        created.unlink(missing_ok=True)
    if kind == "cpu":
        nodes = data.get("nodes") or []
        samples = data.get("samples") or []
        hit_counts: dict[int, int] = {}
        for sample in samples:
            hit_counts[sample] = hit_counts.get(sample, 0) + 1
        deltas = data.get("timeDeltas") or []
        result["samples"] = len(samples)
        result["duration_ms"] = round(sum(deltas) / 1000, 1) if deltas else None
        result["target"] = target.name
        result["hottest"] = _profile_ratio(nodes, hit_counts, len(samples), root)[: max(1, top)]
        if not result["hottest"]:
            result["note"] = "no samples landed in workspace code; the script may be too fast to profile"
    else:
        head = data.get("head") or {}
        tree = head.get("tree") or head or {}
        rows, total = _heap_rows(tree, root)
        result["total_bytes"] = total
        result["samples"] = len(data.get("samples") or [])
        result["hottest"] = rows[: max(1, top)]
        if not rows:
            result["note"] = "no allocation samples were attributed to workspace code"
    return result


def register(registry, config) -> None:
    ws = config.workspace

    @registry.tool(
        "node_diagnose",
        "Debug JavaScript properly: runs a file or snippet under a harness that captures uncaught "
        "exceptions, unhandled rejections and warnings, then returns parsed stack frames with the "
        "surrounding source lines plus concrete fix suggestions. Use this instead of re-running "
        "run_javascript when an error is not obvious.",
        {
            "type": "object",
            "properties": {
                "path": {"type": "string", "description": "File to debug, e.g. 'app/server.js'"},
                "code": {"type": "string", "description": "Snippet to debug instead of a file"},
                "cwd": {"type": "string", "default": "."},
                "args": {"type": "array", "items": {"type": "string"}, "description": "process.argv arguments"},
                "node_flags": {"type": "array", "items": {"type": "string"}, "description": "Extra node flags"},
                "timeout": {"type": "integer", "default": 60},
            },
        },
    )
    def node_diagnose(
        path: str | None = None,
        code: str | None = None,
        cwd: str = ".",
        args: list | None = None,
        node_flags: list | None = None,
        timeout: int = 60,
    ):
        return run_diagnosed(ws, code=code, path=path, cwd=cwd, timeout=timeout, args=args, node_flags=node_flags)

    @registry.tool(
        "node_check",
        "Syntax-check a JavaScript file (or snippet) without executing it. Use after writing or "
        "patching JS to catch parse errors before a run.",
        {
            "type": "object",
            "properties": {
                "path": {"type": "string"},
                "code": {"type": "string"},
                "cwd": {"type": "string", "default": "."},
            },
        },
    )
    def node_check(path: str | None = None, code: str | None = None, cwd: str = "."):
        return syntax_check(ws, path=path, code=code, cwd=cwd)

    @registry.tool(
        "node_profile",
        "Profile a Node script and report the hottest functions: kind='cpu' for time, kind='heap' "
        "for allocation. Use it when code works but is slow or memory-hungry.",
        {
            "type": "object",
            "properties": {
                "path": {"type": "string"},
                "code": {"type": "string"},
                "cwd": {"type": "string", "default": "."},
                "kind": {"type": "string", "enum": ["cpu", "heap"], "default": "cpu"},
                "top": {"type": "integer", "default": 10},
                "timeout": {"type": "integer", "default": 120},
            },
        },
    )
    def node_profile(
        path: str | None = None,
        code: str | None = None,
        cwd: str = ".",
        kind: str = "cpu",
        top: int = 10,
        timeout: int = 120,
    ):
        return cpu_profile(ws, path=path, code=code, cwd=cwd, timeout=timeout, top=top, kind=kind)
